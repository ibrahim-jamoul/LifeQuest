-- LifeQuest Supabase baseline.
-- The Express API remains the only application data entry point.

create table public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  display_name text not null,
  total_xp integer not null default 0,
  current_streak integer not null default 0,
  max_active_goals integer not null default 5,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.life_areas (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name text not null,
  score integer not null default 0 check (score between 0 and 100),
  trend text not null default 'stable' check (trend in ('improving','stable','declining')),
  color text,
  icon text,
  unique (user_id, name)
);

create table public.goals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  life_area_id bigint references public.life_areas(id) on delete set null,
  title text not null,
  description text not null default '',
  category text not null,
  priority text not null default 'medium' check (priority in ('low','medium','high','critical')),
  deadline date,
  status text not null default 'not_started' check (status in ('not_started','in_progress','paused','completed')),
  progress integer not null default 0 check (progress between 0 and 100),
  notes text not null default '',
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.projects (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  life_area_id bigint references public.life_areas(id) on delete set null,
  title text not null,
  description text not null default '',
  status text not null default 'idea',
  priority text not null default 'medium',
  roadmap text not null default '',
  notes text not null default '',
  risk_level text not null default 'low' check (risk_level in ('low','medium','high')),
  next_action text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.milestones (
  id bigint generated by default as identity primary key,
  goal_id bigint references public.goals(id) on delete cascade,
  project_id bigint references public.projects(id) on delete cascade,
  title text not null,
  description text not null default '',
  due_date date,
  is_completed boolean not null default false,
  progress integer not null default 0 check (progress between 0 and 100),
  xp_reward integer not null default 100,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  check (goal_id is not null or project_id is not null)
);

create table public.tasks (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  goal_id bigint references public.goals(id) on delete set null,
  milestone_id bigint references public.milestones(id) on delete set null,
  project_id bigint references public.projects(id) on delete set null,
  title text not null,
  description text not null default '',
  due_date date,
  priority text not null default 'medium' check (priority in ('low','medium','high','critical')),
  estimated_minutes integer,
  is_completed boolean not null default false,
  xp_reward integer not null default 20,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.habits (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  goal_id bigint references public.goals(id) on delete set null,
  name text not null,
  description text not null default '',
  frequency text not null default 'daily' check (frequency in ('daily','weekly','custom')),
  custom_schedule text,
  category text not null,
  current_streak integer not null default 0,
  longest_streak integer not null default 0,
  xp_reward integer not null default 10,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.habit_logs (
  id bigint generated by default as identity primary key,
  habit_id bigint not null references public.habits(id) on delete cascade,
  completed_on date not null,
  is_completed boolean not null default true,
  note text not null default '',
  unique (habit_id, completed_on)
);

create table public.reviews (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  review_type text not null check (review_type in ('weekly','monthly')),
  period_start date not null,
  period_end date not null,
  answers_json jsonb not null default '{}'::jsonb,
  summary_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, review_type, period_start)
);

create table public.notes (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  goal_id bigint references public.goals(id) on delete cascade,
  project_id bigint references public.projects(id) on delete cascade,
  review_id bigint references public.reviews(id) on delete cascade,
  title text not null,
  content text not null default '',
  note_type text not null default 'reflection',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.xp_events (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  source_type text not null,
  source_id bigint,
  amount integer not null,
  reason text not null,
  created_at timestamptz not null default now()
);

create table public.achievements (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text not null,
  icon text,
  xp_reward integer not null default 0,
  condition_json jsonb not null default '{}'::jsonb
);

create table public.user_achievements (
  user_id bigint not null references public.users(id) on delete cascade,
  achievement_id bigint not null references public.achievements(id) on delete cascade,
  unlocked_at timestamptz not null default now(),
  primary key (user_id, achievement_id)
);

create table public.focus_priorities (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  goal_id bigint references public.goals(id) on delete cascade,
  project_id bigint references public.projects(id) on delete cascade,
  week_start date not null,
  priority_type text not null check (priority_type in ('main','secondary')),
  created_at timestamptz not null default now()
);

create table public.weekly_challenges (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null,
  description text not null default '',
  week_start date not null,
  target integer not null default 1,
  progress integer not null default 0,
  xp_reward integer not null default 100,
  is_completed boolean not null default false
);

create table public.parent_profiles (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references public.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

