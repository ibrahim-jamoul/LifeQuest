-- Data API is enabled on the project, but LifeQuest does not directly query it.
-- Explicit RLS and revoked API roles provide defense in depth.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'users','life_areas','goals','projects','milestones','tasks','habits','habit_logs',
    'notes','reviews','xp_events','achievements','user_achievements','focus_priorities',
    'weekly_challenges','child_profiles','parent_profiles','parent_child_missions',
    'discovery_domains','discovery_challenges','discovery_completions','village_state',
    'auth_sessions','school_campaigns','campaign_chapters','notifications','user_preferences'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
  end loop;
end
$$;

